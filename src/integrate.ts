/**
 * 编辑器集成：内容全部集中在 .quality-center/，编辑器目录里只留「指针文件」。
 *
 * 设计要点：
 * - 业务目录零侵入：规则/MCP 都是编辑器强制路径上的薄封装（≤10 行），不复制流程知识；
 * - 生成物可重复执行（幂等），带托管块标记，不覆盖用户自己的规则；
 * - --check 只比对不写，供 CI 发现「策略改了但适配器没同步」；
 * - 启动器 shim 让 MCP 配置不再带扩展版本号，升级扩展不需要改五个编辑器；
 * - 默认只为检测到的编辑器生成适配器；AGENTS.md / .mcp.json 这类兜底文件需显式 --fallback；
 * - 扫描结果与升级计划都在 .quality-center/ 内，由它自带的 .gitignore 忽略，不污染仓库根。
 */
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { defaultPolicyDocument } from './upgradePolicy';
import { PACKAGE_ROOT } from './agentOps';

export type IntegrateMode = 'auto' | 'all';

export interface IntegrateOptions {
  mode: IntegrateMode;
  check: boolean;
  /** 是否额外生成 AGENTS.md / 根 .mcp.json 这类兜底文件（默认否，保持仓库干净） */
  fallback?: boolean;
}

export interface IntegrateFile {
  file: string;
  action: 'created' | 'updated' | 'unchanged' | 'drift' | 'missing';
}

export interface IntegrateResult {
  ok: boolean;
  files: IntegrateFile[];
  notes: string[];
}

const SKILL_REL = path.join('.quality-center', 'skills', 'quality-center-java-upgrade', 'SKILL.md');
const POLICY_REL = path.join('.quality-center', 'upgrade-policy.json');
const CLI_REL = path.join('.quality-center', 'bin', 'qc.cjs');

const BEGIN = '<!-- quality-center:begin (generated, do not edit inside) -->';
const END = '<!-- quality-center:end -->';

