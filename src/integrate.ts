const LAUNCHER_CMD = ['@echo off', 'node "%~dp0qc.cjs" %*', ''].join('\n');
const LAUNCHER_SH = ['#!/bin/sh', 'exec node "$(dirname "$0")/qc.cjs" "$@"', ''].join('\n');

/**
 * Trae 不会展开 MCP 配置里的 ${workspaceFolder}，会把字面量直接传给 node。
 * 因此这里写项目内的绝对启动器路径和 cwd；每个仓库的配置本来由本仓库生成，可移植性由重新接入保证。
 */
function mcpServer(root: string) {
  return {
    command: 'node',
    args: [path.join(root, '.quality-center', 'bin', 'qc.cjs'), 'mcp'],
    cwd: path.resolve(root)
  };
}

function ruleDocument(): string {
  return ['---', 'description: 质量中心：按 quality-center 标准做依赖与配置安全整改（先出计划再改文件）',
    'globs:', '  - "pom.xml"', '  - "**/application*.yml"', '  - "**/*.java"', 'alwaysApply: false', '---', '', RULE_BODY, ''].join('\n');
}

function instructionsDocument(): string {
  return [
    '---',
    'description: 质量中心升级与配置安全整改的标准流程',
    'applyTo: "**"',
    '---',
    '',
    RULE_BODY,
    ''
  ].join('\n');
}

function agentsBlock(): string {
  return [BEGIN, '## 质量中心（quality-center）', '', RULE_BODY, '', END, ''].join('\n');
}

function writeManaged(file: string, content: string, check: boolean): IntegrateFile['action'] {
  if (!fs.existsSync(file)) {
    if (check) {
      return 'missing';
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, 'utf8');
    return 'created';
  }
  const current = fs.readFileSync(file, 'utf8');
  if (current === content) {
    return 'unchanged';
  }
  if (check) {
    return 'drift';
  }
  fs.writeFileSync(file, content, 'utf8');
  return 'updated';
}

/** 在 markdown 里维护托管块：只替换块内内容，块外的用户内容原样保留 */
function upsertBlock(file: string, block: string, check: boolean): IntegrateFile['action'] {
  const body = `${block}`;
  if (!fs.existsSync(file)) {
    if (check) {
      return 'missing';
    }
    fs.writeFileSync(file, body, 'utf8');
    return 'created';
  }
  const current = fs.readFileSync(file, 'utf8');
  const begin = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  let next: string;
  if (begin >= 0 && end > begin) {
    next = current.slice(0, begin) + body + current.slice(end + END.length + 1);
  } else {
    next = `${current.replace(/\s*$/, '')}\n\n${body}`;
  }
  if (next === current) {
    return 'unchanged';
  }
  if (check) {
    return 'drift';
  }
  fs.writeFileSync(file, next, 'utf8');
  return 'updated';
}

/** MCP 配置：合并 server 条目，不覆盖用户其它 MCP 服务 */
function upsertMcpJson(
  file: string,
  shape: 'mcpServers' | 'servers',
  root: string,
  check: boolean
): IntegrateFile['action'] {
  const server = mcpServer(root);
  const entry =
    shape === 'servers'
      ? { type: 'stdio', ...server }
      : { ...server };
  let doc: Record<string, unknown> = {};
  const existed = fs.existsSync(file);
  if (existed) {
    try {
      doc = JSON.parse(fs.readFileSync(file, 'utf8')) as Record<string, unknown>;
    } catch {
      return 'drift';
    }
  }
  const servers = (doc[shape] as Record<string, unknown> | undefined) ?? {};
  const current = JSON.stringify(servers['quality-center']);
  const expected = JSON.stringify(entry);
  if (current === expected) {
    return 'unchanged';
  }
  if (check) {
    return existed ? 'drift' : 'missing';
  }
  servers['quality-center'] = entry;
  doc[shape] = servers;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(doc, null, 2)}\n`, 'utf8');
  return existed ? 'updated' : 'created';
}

function detect(root: string): Set<string> {
  const found = new Set<string>();
  if (fs.existsSync(path.join(root, '.trae'))) {
    found.add('trae');
  }
  if (fs.existsSync(path.join(root, '.cursor'))) {
    found.add('cursor');
  }
  if (fs.existsSync(path.join(root, '.vscode'))) {
    found.add('vscode');
  }
  if (fs.existsSync(path.join(root, '.github'))) {
    found.add('github');
  }
  // 项目里还没有对应目录，但本机装了该编辑器时也算使用方：
  // Trae 的项目规则目录要等首次写入才出现，只靠目录判断会漏掉真实用户。
  const home = os.homedir();
  if (!found.has('trae') && (fs.existsSync(path.join(home, '.trae-cn')) || fs.existsSync(path.join(home, '.trae')))) {
    found.add('trae');
  }
  if (!found.has('cursor') && fs.existsSync(path.join(home, '.cursor'))) {
    found.add('cursor');
  }
  return found;
}

export function integrate(root: string, options: IntegrateOptions): IntegrateResult {
  const files: IntegrateFile[] = [];
  const notes: string[] = [];
  const check = options.check;

  const record = (file: string, action: IntegrateFile['action'], label?: string): void => {
    files.push({ file: path.relative(root, file).split(path.sep).join('/') || label || file, action });
  };

  // 1. 单一事实源
  const policyFile = path.join(root, POLICY_REL);
  if (fs.existsSync(policyFile)) {
    record(policyFile, 'unchanged');
  } else if (check) {
    record(policyFile, 'missing');
  } else {
    fs.mkdirSync(path.dirname(policyFile), { recursive: true });
    fs.writeFileSync(policyFile, `${JSON.stringify(defaultPolicyDocument(root), null, 2)}\n`, 'utf8');
    record(policyFile, 'created');
    notes.push('已写入默认策略：请按项目实际约束调整 frameworkTargets / forbiddenPackages / buildGate');
  }

  record(path.join(root, CLI_REL), writeManaged(path.join(root, CLI_REL), LAUNCHER_CJS, check));
  record(path.join(root, '.quality-center', 'bin', 'qc.cmd'), writeManaged(path.join(root, '.quality-center', 'bin', 'qc.cmd'), LAUNCHER_CMD, check));
  record(path.join(root, '.quality-center', 'bin', 'qc.sh'), writeManaged(path.join(root, '.quality-center', 'bin', 'qc.sh'), LAUNCHER_SH, check));
  record(
    path.join(root, '.quality-center', '.gitignore'),
    writeManaged(path.join(root, '.quality-center', '.gitignore'), NESTED_GITIGNORE, check)
  );

  const skillSource = path.join(PACKAGE_ROOT, 'skills', 'quality-center-java-upgrade', 'SKILL.md');
  const skillTarget = path.join(root, SKILL_REL);
  if (fs.existsSync(skillSource)) {
    record(skillTarget, writeManaged(skillTarget, fs.readFileSync(skillSource, 'utf8'), check));
  } else {
    notes.push(`扩展目录里没有 Skill 源文件：${skillSource}`);
    record(skillTarget, 'missing');
  }

  // 2. 编辑器适配器（只写检测到的编辑器；内容都指向 .quality-center/，这里只是薄封装）
  const targets = options.mode === 'all' ? new Set(['trae', 'cursor', 'vscode', 'github']) : detect(root);
  if (options.mode === 'auto' && targets.size === 0) {
    notes.push('未检测到任何编辑器；只写了 .quality-center/ 数据目录，可用 integrate --all 全量铺开');
  }

  const rule = ruleDocument();
  if (targets.has('trae')) {
    record(path.join(root, '.trae', 'rules', 'quality-center.md'), writeManaged(path.join(root, '.trae', 'rules', 'quality-center.md'), rule, check));
    record(path.join(root, '.trae', 'mcp.json'), upsertMcpJson(path.join(root, '.trae', 'mcp.json'), 'mcpServers', root, check));
    notes.push('Trae：项目级 MCP 需在 设置 > MCP 打开「启用项目级 MCP」并确认信任');
  }
  if (targets.has('cursor')) {
    record(path.join(root, '.cursor', 'rules', 'quality-center.mdc'), writeManaged(path.join(root, '.cursor', 'rules', 'quality-center.mdc'), rule, check));
    record(path.join(root, '.cursor', 'mcp.json'), upsertMcpJson(path.join(root, '.cursor', 'mcp.json'), 'mcpServers', root, check));
  }
  if (targets.has('vscode')) {
    record(path.join(root, '.vscode', 'mcp.json'), upsertMcpJson(path.join(root, '.vscode', 'mcp.json'), 'servers', root, check));
  }
  if (targets.has('github')) {
    record(
      path.join(root, '.github', 'instructions', 'quality-center.instructions.md'),
      writeManaged(path.join(root, '.github', 'instructions', 'quality-center.instructions.md'), instructionsDocument(), check)
    );
  }

  // 3. 兜底文件：仅当显式要求时生成，避免在仓库根多出 AGENTS.md / .mcp.json
  if (options.fallback) {
    record(path.join(root, '.mcp.json'), upsertMcpJson(path.join(root, '.mcp.json'), 'mcpServers', root, check));
    record(path.join(root, 'AGENTS.md'), upsertBlock(path.join(root, 'AGENTS.md'), agentsBlock(), check));
  } else {
    notes.push('未写 AGENTS.md / 根 .mcp.json（兜底文件默认关闭）；需要时加 --fallback');
  }

  const drifted = files.filter((item) => item.action === 'drift' || item.action === 'missing');
  const notGenerated: string[] = [];
  if (!targets.has('trae')) {
    notGenerated.push('.trae（Trae）');
  }
  if (!targets.has('cursor')) {
    notGenerated.push('.cursor（Cursor）');
  }
  if (!targets.has('vscode')) {
    notGenerated.push('.vscode/mcp.json（VS Code）');
  }
  if (!targets.has('github')) {
    notGenerated.push('.github/instructions（Copilot）');
  }
  if (options.mode === 'auto' && notGenerated.length > 0) {
    notes.push(`未生成：${notGenerated.join('、')}；需要一次铺开时执行 integrate --all`);
  }
  return { ok: check ? drifted.length === 0 : true, files, notes };
}
